#!/usr/bin/env python3
"""Generate the frozen PS3.15 profile matrix used by the Rust core.

Run with:

    uv run --with pandas==2.3.3 --with lxml==6.0.2 tools/generate_profile.py

The source URL deliberately points at ``current`` but generation fails unless the
published page identifies itself as DICOM 2026c. This prevents a future standard
edition from silently changing the frozen rule table.
"""

from __future__ import annotations

from pathlib import Path
import re
from urllib.request import urlopen

import pandas as pd


EDITION = "2026c"
SOURCE_URL = (
    "https://dicom.nema.org/medical/dicom/current/output/chtml/part15/chapter_e.html"
)
SAFE_PRIVATE_URL = (
    "https://dicom.nema.org/medical/dicom/current/output/chtml/part15/sect_e.3.10.html"
)
OUTPUT = Path(__file__).parents[1] / "core/src/profile_generated.rs"

OPTION_COLUMNS = (
    "Rtn. Safe Priv. Opt.",
    "Rtn. UIDs Opt.",
    "Rtn. Dev. Id. Opt.",
    "Rtn. Inst. Id. Opt.",
    "Rtn. Pat. Chars. Opt.",
    "Rtn. Long. Full Dates Opt.",
    "Rtn. Long. Modif. Dates Opt.",
    "Clean Desc. Opt.",
    "Clean Struct. Cont. Opt.",
    "Clean Graph. Opt.",
)
DEFAULT_COLUMNS = {
    "Rtn. Pat. Chars. Opt.",
    "Rtn. Long. Modif. Dates Opt.",
    "Clean Desc. Opt.",
}


def action(value: str) -> str:
    variants = {
        "X": "Remove",
        "Z": "Empty",
        "D": "Dummy",
        "U": "RemapUid",
        "K": "Keep",
        "C": "Clean",
        "Z/D": "Dummy",
        "X/Z": "Empty",
        "X/D": "Dummy",
        "X/Z/D": "Dummy",
        "X/Z/U*": "RemapUid",
    }
    try:
        return f"ProfileAction::{variants[value]}"
    except KeyError as error:
        raise ValueError(f"unknown PS3.15 action {value!r}") from error


def rust_string(value: str) -> str:
    return (
        value.replace("\u200b", "")
        .replace("\\", "\\\\")
        .replace('"', '\\"')
    )


def main() -> None:
    page = urlopen(SOURCE_URL).read()
    if f"DICOM PS3.15 {EDITION}".encode() not in page:
        raise SystemExit(f"expected DICOM PS3.15 {EDITION} at {SOURCE_URL}")

    table = next(
        frame
        for frame in pd.read_html(page)
        if "Basic Prof." in frame.columns and "Rtn. Pat. Chars. Opt." in frame.columns
    ).fillna("")

    lines = [
        "// Generated by tools/generate_profile.py from DICOM PS3.15 2026c Table E.1-1.",
        "// Do not edit by hand.",
        "",
        "#[rustfmt::skip]",
        "pub(super) const PROFILE_RULES: &[ProfileRule] = &[",
    ]
    generated_rows: list[tuple[int, str, str, str, list[str]]] = []
    for _, row in table.iterrows():
        match = re.fullmatch(r"\(([0-9A-Fa-f]{4}),([0-9A-Fa-f]{4})\)", str(row["Tag"]))
        if match is None:
            continue
        tag = "".join(match.groups()).upper()
        basic = action(str(row["Basic Prof."]).strip())
        options = []
        default_actions = []
        for column in OPTION_COLUMNS:
            value = str(row[column]).strip()
            options.append("None" if not value else f"Some({action(value)})")
            if column in DEFAULT_COLUMNS and value:
                default_actions.append(action(value))
        if len(set(default_actions)) > 1:
            raise ValueError(f"conflicting default actions for {row['Attribute Name']}")
        effective = default_actions[0] if default_actions else basic
        name = rust_string(str(row["Attribute Name"]))
        option_text = ", ".join(options)
        generated_rows.append((int(tag, 16), name, effective, basic, options))
    generated_rows.sort(key=lambda item: item[0])
    for tag, name, effective, basic, options in generated_rows:
        option_text = ", ".join(options)
        lines.append(
            f'    ProfileRule::new(0x{tag:08X}, "{name}", {effective}, {basic}, [{option_text}]),'
        )
    lines.append("];")
    lines.append("")
    group_ranges: dict[int, tuple[int, int]] = {}
    for index, (tag, *_rest) in enumerate(generated_rows):
        group = tag >> 16
        start, _ = group_ranges.get(group, (index, index))
        group_ranges[group] = (start, index + 1)
    lines.extend(
        [
            "#[inline]",
            "pub(super) fn profile_rule_group(group: u16) -> &'static [ProfileRule] {",
            "    match group {",
        ]
    )
    for group, (start, end) in sorted(group_ranges.items()):
        lines.append(f"        0x{group:04X} => &PROFILE_RULES[{start}..{end}],")
    lines.extend(["        _ => &[],", "    }", "}", ""])

    option_conflicts: dict[tuple[int, int], tuple[int, str]] = {}
    for tag, name, _effective, _basic, options in generated_rows:
        for left in range(len(options)):
            for right in range(left + 1, len(options)):
                if (
                    options[left] != "None"
                    and options[right] != "None"
                    and options[left] != options[right]
                ):
                    option_conflicts.setdefault((left, right), (tag, name))
    lines.extend(
        [
            "#[rustfmt::skip]",
            "pub(super) const OPTION_CONFLICTS: &[(u8, u8, u32, &str)] = &[",
        ]
    )
    for (left, right), (tag, name) in sorted(option_conflicts.items()):
        lines.append(
            f'    ({left}, {right}, 0x{tag:08X}, "{rust_string(name)}"),'
        )
    lines.extend(["];", ""])

    safe_private_page = urlopen(SAFE_PRIVATE_URL).read()
    if f"DICOM PS3.15 {EDITION}".encode() not in safe_private_page:
        raise SystemExit(f"expected DICOM PS3.15 {EDITION} at {SAFE_PRIVATE_URL}")
    safe_private_table = next(
        frame
        for frame in pd.read_html(safe_private_page)
        if "Data Element" in frame.columns and "Private Creator" in frame.columns
    ).fillna("")
    safe_private_attributes: set[tuple[str, int]] = set()
    for _, row in safe_private_table.iterrows():
        match = re.fullmatch(
            r"\([0-9A-Fa-f]{4},xx([0-9A-Fa-f]{2})\)",
            str(row["Data Element"]).strip(),
        )
        creator = str(row["Private Creator"]).strip()
        if match is not None and creator:
            safe_private_attributes.add((creator, int(match.group(1), 16)))

    lines.extend(
        [
            "#[rustfmt::skip]",
            "pub(super) const SAFE_PRIVATE_ATTRIBUTES: &[(&str, u8)] = &[",
        ]
    )
    for creator, offset in sorted(safe_private_attributes):
        lines.append(f'    ("{rust_string(creator)}", 0x{offset:02X}),')
    lines.extend(["];", ""])

    if len(generated_rows) != 652:
        raise ValueError(f"expected 652 exact rules, found {len(generated_rows)}")
    if len(safe_private_attributes) != 457:
        raise ValueError(
            f"expected 457 unique safe-private entries, found {len(safe_private_attributes)}"
        )
    if len(option_conflicts) != 2:
        raise ValueError(
            f"expected 2 conflicting option pairs, found {len(option_conflicts)}"
        )
    OUTPUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
